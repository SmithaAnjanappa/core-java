package com.xworkz.policeapp.police;

public class Police {
    private int policeId;
    private String policeName;
    private String typeOfPolice;
    private String noOfStars;
    private  String workTimings;
    private int noOfPistol;

    public int getPoliceId() {
        return policeId;
    }

    public void setPoliceId(int policeId) {
        this.policeId = policeId;
    }

    public String getPoliceName() {
        return policeName;
    }

    public void setPoliceName(String policeName) {
        this.policeName = policeName;
    }

    public String getTypeOfPolice() {
        return typeOfPolice;
    }

    public void setTypeOfPolice(String typeOfPolice) {
        this.typeOfPolice = typeOfPolice;
    }

    public String getNoOfStars() {
        return noOfStars;
    }

    public void setNoOfStars(String noOfStars) {
        this.noOfStars = noOfStars;
    }

    public String getWorkTimings() {
        return workTimings;
    }

    public void setWorkTimings(String workTimings) {
        this.workTimings = workTimings;
    }

    public int getNoOfPistol() {
        return noOfPistol;
    }

    public void setNoOfPistol(int noOfPistol) {
        this.noOfPistol = noOfPistol;
    }
}
